const TARGET_RT: f64 = 0.8851803541183472;
const WINDOW: f64 = 0.2;
const REFERENCE_AREA: f64 = 10521.0;

fn options() -> FindPeaksOptions {
    FindPeaksOptions {
        auto_noise: true,
        auto_baseline: true,
        min_snr: 1.0,
        ..Default::default()
    }
}

#[test]
fn dip_on_the_top_does_not_cut_the_peak() {
    let eic = DataXY {
        x: TIME.to_vec(),
        y: INTENSITY.to_vec(),
    };
    let peak = get_peak(
        &eic,
        &Roi {
            rt: TARGET_RT,
            range: WINDOW,
        },
        &options(),
    );
    let scan = TIME[1] - TIME[0];

    assert!(
        peak.rt - peak.from > 2.0 * scan && peak.to - peak.rt > 2.0 * scan,
        "edges [{}, {}] must not sit on the apex {}",
        peak.from,
        peak.to,
        peak.rt
    );
    assert!(
        (peak.integral / REFERENCE_AREA - 1.0).abs() <= 0.1,
        "integral {} must match the whole peak area {REFERENCE_AREA}",
        peak.integral
    );
}
